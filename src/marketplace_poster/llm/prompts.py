def variation_hint(index: int) -> str | None:
    if index <= 0:
        return None
    return VARIATION_HINTS[(index - 1) % len(VARIATION_HINTS)]


def build_system_prompt(platform: PlatformRulePack) -> str:
    shot = _FEW_SHOT[platform.id]
    index_note = (
        "Описание индексируется поиском."
        if platform.search_indexes_description
        else "Описание НЕ индексируется. Сила пакета — в title, tags и attributes."
    )
    return (
        f"{_SHARED_RULES}\n\n"
        f"Площадка: {platform.display_name}.\n"
        f"Название: максимум {platform.max_title} символов, цель "
        f"{platform.target_title_min}–{platform.target_title_max}. "
        f"Формула: {platform.title_formula}.\n"
        f"Описание: цель {platform.target_description_min}–{platform.target_description_max}, "
        f"потолок {platform.max_description}. {index_note}\n"
        f"Теги: {platform.min_tags}–{platform.max_tags} штук.\n"
        f"{platform.extra_instructions}\n"
        f"Календарные поводы, если уместны по фактам: {', '.join(OCCASION_HINTS)}.\n\n"
        f"Пример хорошего пакета (ориентир стиля, не копируй товар):\n"
        f"{shot.model_dump_json(ensure_ascii=False)}"
    )


def build_user_prompt(
    platform: PlatformRulePack,
    brief: ProductBrief,
    *,
    hint: str | None = None,
    repair_issues: list[str] | None = None,
) -> str:
    occasions = suggest_occasions(brief.facts)
    parts = [
        f"Площадка: {platform.display_name}.",
        "Факты от селлера:",
        brief.facts.strip() or "(только фото, фактов нет — опиши только то, что видно)",
    ]
    if occasions:
        parts.append("Поводы, которые уже следуют из фактов: " + ", ".join(occasions))
    if hint:
        parts.append(hint)
        parts.append("Не повторяй формулировки предыдущей версии дословно.")
    if repair_issues:
        parts.append(
            "Предыдущий черновик нарушил правила. Перепиши целиком, уложись в лимиты. "
            "Проблемы: " + "; ".join(repair_issues)
        )
    if brief.photo_file_id:
        parts.append("К сообщению приложено фото товара — сверь цвет, крой, видимые детали.")
    parts.append("Верни JSON SeoPackage.")
    return "\n".join(parts)
