def preview_sku() -> dict[str, str]:
    """Валидирует золотые пакеты и собирает HTML, как в Telegram."""
    rendered: dict[str, str] = {}
    for platform_id, package in GOLDEN_PACKAGES.items():
        platform = get_platform(platform_id)
        result = validate_package(package, platform)
        if result.needs_llm_repair:
            raise ValueError(f"{platform.display_name}: {result.issues}")
        rendered[platform.id.value] = format_result_html(result.package, platform)
    return rendered


def main() -> None:
    print("SKU:\n", SAMPLE_FACTS, sep="")
    print("Площадок в реестре:", ", ".join(p.display_name for p in PLATFORMS.values()))
    print()
    for platform_id, html in preview_sku().items():
        platform = get_platform(platform_id)
        package = validate_package(GOLDEN_PACKAGES[platform.id], platform).package
        print("=" * 60)
        print(html.replace("<b>", "").replace("</b>", ""))
        print("-" * 60)
        print(format_plain_package(package))
        print()


if __name__ == "__main__":
    main()
