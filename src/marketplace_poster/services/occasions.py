"""Календарные и ролевые теги — закрывают пропуск «подарок маме» из гипотезы."""

from __future__ import annotations

OCCASION_HINTS: tuple[str, ...] = (
    "подарок маме",
    "подарок папе",
    "подарок коллеге",
    "подарок мужчине",
    "подарок женщине",
    "день рождения",
    "8 марта",
    "23 февраля",
    "новый год",
)

_FACT_TRIGGERS: tuple[tuple[tuple[str, ...], tuple[str, ...]], ...] = (
    (("маме", "мамы", "мама", "женщин"), ("подарок маме", "подарок женщине", "8 марта")),
    (("папе", "папа", "мужчин"), ("подарок папе", "подарок мужчине", "23 февраля")),
    (("коллег",), ("подарок коллеге",)),
    (("день рождения", "др ", "др,"), ("день рождения",)),
    (("новый год", "новогодн", "нг "), ("новый год",)),
    (("8 марта", "8марта"), ("8 марта", "подарок женщине")),
    (("23 февраля", "23февраля"), ("23 февраля", "подарок мужчине")),
)


def suggest_occasions(facts: str) -> list[str]:
    """Подсказывает поводы, если они уже видны в фактах селлера."""
    lowered = f" {facts.lower()} "
    found: list[str] = []
    for needles, hints in _FACT_TRIGGERS:
        if any(needle in lowered for needle in needles):
            for hint in hints:
                if hint not in found:
                    found.append(hint)
    return found
